"""One-time, read-only map inspection; emit server-owned placement and navigation tables."""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'tests/reference'), str(ROOT / 'tests/reference/Business/vendor')]

from Business.scripts import map_data, navmesh_resource, spawn_resource
from Business.scripts.navigation import NavMesh
from Business.scripts.vfs_resource import readResource


def renderMap(spawns, respawns):
    spawns = spawn_resource.validatePoints(spawns, {1: 10, 2: 10})
    respawns = spawn_resource.validatePoints(respawns, {1: 14, 2: 12})
    lines = ['"""Server-owned Luoyang map configuration; no runtime client reads.',
             'Generated by scripts/export_map_config.py.', '"""', '']
    for name in ('RESOURCE_ID', 'MAP_NAME', 'POSITION', 'ENEMY_POSITION'):
        lines.append(f'{name} = {getattr(map_data, name)!r}')
    for name, camps in (('SPAWNS', spawns), ('RESPAWNS', respawns)):
        lines.extend(['', name + ' = {'])
        for camp, points in sorted(camps.items()):
            lines.append(f'    {camp}: (')
            lines.extend(f'        {point!r},' for point in points)
            lines.append('    ),')
        lines.append('}')
    return '\n'.join([*lines, ''])


def renderNavigation(resource):
    NavMesh.fromResource(resource)
    lines = ['"""Server-owned Luoyang navigation; original indices and precision retained.',
             'Generated by scripts/export_map_config.py.',
             'VERTICES: (x, y, z). EDGES: (a, b, oppositeEdge, oppositeFace).',
             'FACES: (startEdgeIndex, numEdges, numUserEdges).', '"""']
    for name, rows in (
            ('VERTICES', (tuple(vertex[:3]) for vertex in resource['vertices'])),
            ('EDGES', (tuple(edge[key] for key in navmesh_resource.EDGE_FIELDS) for edge in resource['edges'])),
            ('FACES', (tuple(face[key] for key in navmesh_resource.FACE_FIELDS) for face in resource['faces']))):
        lines.extend(['', name + ' = ('])
        lines.extend(f'    {row!r},' for row in rows)
        lines.append(')')
    return '\n'.join([*lines, ''])


def export(directory):
    spawns, respawns = readResource(directory, 'map.vfs', spawn_resource.SPAWN_PATH,
        lambda data: (spawn_resource.parseSpawns(data), spawn_resource.parseRespawns(data)))
    navigation = navmesh_resource.readNavigationResource(directory)
    return {'map_data.py': renderMap(spawns, respawns),
            'map_navigation_data.py': renderNavigation(navigation)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client-directory', type=Path, required=True, help='selected absolute Bin directory')
    parser.add_argument('--output', type=Path, required=True, help='new directory; existing directories are not overwritten')
    args = parser.parse_args()
    if not args.client_directory.is_absolute():
        parser.error('--client-directory must be absolute')
    files = export(str(args.client_directory))
    args.output.mkdir()
    for name, content in files.items():
        with (args.output / name).open('x', encoding='utf-8', newline='\n') as output:
            output.write(content)
    print(f'map={map_data.RESOURCE_ID} files={len(files)} bytes={sum(len(text.encode("utf-8")) for text in files.values())}')


if __name__ == '__main__':
    main()
